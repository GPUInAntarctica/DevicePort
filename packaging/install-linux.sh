#!/usr/bin/env bash
# Register DevicePort with the Linux desktop so double-clicking just works.
# Run once from a terminal:
#   bash packaging/install-linux.sh
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/.." && pwd)"

# Find the AppImage: in dist/ or next to this script.
APPIMAGE=""
for c in "$ROOT/dist/DevicePort-x86_64.AppImage" "$HERE/DevicePort-x86_64.AppImage"; do
  [ -f "$c" ] && APPIMAGE="$c" && break
done
if [ -z "$APPIMAGE" ]; then
  echo "Cannot find DevicePort-x86_64.AppImage. Run 'make appimage' first." >&2
  exit 1
fi
APPIMAGE="$(cd "$(dirname "$APPIMAGE")" && pwd)/$(basename "$APPIMAGE")"
chmod +x "$APPIMAGE"

APPDIR="$HOME/.local/share/applications"
ICONDIR="$HOME/.local/share/icons/hicolor/256x256/apps"
BINDIR="$HOME/.local/bin"
DESKTOPDIR="$HOME/Desktop"
mkdir -p "$APPDIR" "$ICONDIR" "$BINDIR"

# Install a stable copy so moving/deleting the download doesn't break the launcher.
TARGET="$BINDIR/DevicePort-x86_64.AppImage"
if [ "$APPIMAGE" != "$TARGET" ]; then
  cp "$APPIMAGE" "$TARGET"
  chmod +x "$TARGET"
fi
cp "$HERE/appimage/AppDir/usr/share/icons/hicolor/256x256/apps/deviceport.png" \
   "$ICONDIR/deviceport.png"

# GUI launcher: starts a local demo network with the bundled binary, then opens
# the browser. Works with any AppImage version and needs no terminal/root.
WRAPPER="$BINDIR/deviceport-gui"
cat > "$WRAPPER" <<EOF
#!/usr/bin/env bash
# DevicePort desktop launcher (generated by packaging/install-linux.sh).
APP="$TARGET"
EXTRACT=""
if [ "\${1:-}" = "--no-fuse" ]; then
  EXTRACT="APPIMAGE_EXTRACT_AND_RUN=1"
fi
run() {
  if [ -n "\$EXTRACT" ]; then env APPIMAGE_EXTRACT_AND_RUN=1 "\$APP" "\$@"
  else "\$APP" "\$@"; fi
}
SRV_PID=""; NODE_PID=""
cleanup() {
  [ -n "\$SRV_PID" ] && kill "\$SRV_PID" 2>/dev/null || true
  [ -n "\$NODE_PID" ] && kill "\$NODE_PID" 2>/dev/null || true
}
trap cleanup EXIT INT TERM
run server --listen 127.0.0.1:19000 --admin 127.0.0.1:19001 --subnet 10.66.0.0/24 >/dev/null 2>&1 &
SRV_PID=\$!
sleep 1
run node --server 127.0.0.1:19000 --name "Desktop \$(hostname)" --tun userspace --gui 127.0.0.1:9050 >/dev/null 2>&1 &
NODE_PID=\$!
for _ in \$(seq 1 40); do
  if (echo > /dev/tcp/127.0.0.1/9050) >/dev/null 2>&1; then
    xdg-open http://127.0.0.1:9050/ >/dev/null 2>&1 &
    wait "\$NODE_PID" 2>/dev/null || true
    exit 0
  fi
  sleep 0.25
done
echo "DevicePort: control panel did not start" >&2
exit 1
EOF
chmod +x "$WRAPPER"

ENTRY="$APPDIR/deviceport.desktop"
cat > "$ENTRY" <<EOF
[Desktop Entry]
Type=Application
Name=DevicePort
GenericName=IPv6 Overlay VPN
Comment=DevicePort control panel (local demo network)
Exec=$WRAPPER
Icon=deviceport
Terminal=false
Categories=Network;X-VPN;
StartupNotify=false
EOF
chmod +x "$ENTRY"
if [ -d "$DESKTOPDIR" ] && [ -w "$DESKTOPDIR" ]; then
  cp "$ENTRY" "$DESKTOPDIR/DevicePort.desktop"
  chmod +x "$DESKTOPDIR/DevicePort.desktop"
elif [ -d "$DESKTOPDIR" ]; then
  echo "Note: $DESKTOPDIR is not writable; skipping Desktop icon (launcher still registered)." >&2
fi

# Register as the handler for AppImage files and refresh caches.
xdg-mime default deviceport.desktop application/vnd.appimage 2>/dev/null || true
xdg-mime default deviceport.desktop application/x-appimage 2>/dev/null || true
update-desktop-database "$APPDIR" 2>/dev/null || true
gtk-update-icon-cache -q "$HOME/.local/share/icons/hicolor" 2>/dev/null || true

echo "DevicePort installed."
echo "  AppImage: $TARGET"
echo "  Launcher: $WRAPPER"
echo "  Desktop entry: $ENTRY"
echo "Now double-click DevicePort on the Desktop (or any .AppImage file)."
echo "It opens a browser window with the control panel; no terminal or root needed."
